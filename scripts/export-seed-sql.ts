/**
 * Dump the seeded local SQLite data as INSERT statements so it can be loaded into D1.
 * Usage: npm run db:seed && npm run db:export-seed  ->  writes data/seed.sql
 * Then:  npx wrangler d1 execute boq-db --remote --file data/seed.sql
 */
import { writeFileSync } from 'node:fs';
import { createClient } from '@libsql/client';

// Parent tables first so foreign keys resolve.
const TABLES = ['users', 'projects', 'tasks', 'activity_logs'];

const quote = (v: unknown) =>
	v === null || v === undefined
		? 'NULL'
		: typeof v === 'number' || typeof v === 'bigint'
			? String(v)
			: `'${String(v).replaceAll("'", "''")}'`;

async function main() {
	const client = createClient({ url: process.env.DATABASE_URL ?? 'file:local.db' });
	const lines = ['-- Generated by scripts/export-seed-sql.ts', ...[...TABLES].reverse().map((t) => `DELETE FROM ${t};`)];
	for (const table of TABLES) {
		const { rows, columns } = await client.execute(`SELECT * FROM ${table}`);
		for (const row of rows) {
			lines.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES (${columns.map((c) => quote(row[c])).join(', ')});`);
		}
	}
	writeFileSync('data/seed.sql', lines.join('\n') + '\n');
	console.log(`Wrote data/seed.sql (${lines.length} lines)`);
	client.close();
}

main();
